#!/usr/bin/env python3
"""Write the authority a task requires into the API documents.

The required authority of every task is defined in one place, the task
tables of the server source (task_info[] in cm_server_util.cpp and
ext_task_info[] in cm_server_extend_interface.cpp). This script copies it
into the documents so that they cannot drift apart:

  * each task document (docs/api/<task>.md) gets the line
        Permissions required to run this task: ...
    right before "## Request JSON Syntax";
  * the Permission column of the interface tables in docs/api/README.md is
    rewritten, rows of tasks that no longer exist are dropped, and tasks
    that have no row are listed in a generated table at the end.

Usage:
    gen_task_authority.py            rewrite the documents
    gen_task_authority.py --check    only compare; exit 1 if a document is out
                                     of date (for tests and CI)

Restrictions other than the required authority (own password only, protected
files, ...) are written by hand under the generated line; the script only
manages the line itself.
"""

import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                     "..", "..", ".."))
SRC = os.path.join(ROOT, "server", "src")
DOCS = os.path.join(ROOT, "docs", "api")
TABLES = (("cm_server_util.cpp", "socket, http"),
          ("cm_server_extend_interface.cpp", "http"))

LINE_PREFIX = "Permissions required to run this task: "
SECTION_BEGIN = "<!-- generated by tools/gen_task_authority.py: tasks without a document -->"
SECTION_END = "<!-- end of generated table -->"

# Authority bits in the order they are written.
BITS = (("AU_DBC", "DBC"), ("AU_DBO", "DBO"), ("AU_BRK", "BRK"),
        ("AU_MON", "MON"), ("AU_JOB", "JOB"), ("AU_VAR", "VAR"),
        ("AU_ADMIN", "ADMIN"))

# Tasks whose rule is not the plain table value: (document line, table cell).
OVERRIDES = {
    # token validation and the authority check both skip these
    "login": ("none (no login required)", "no login required"),
    "getcmsenv": ("none (no login required)", "no login required"),
    # handled before the task tables are consulted
    "gettaskstatus": ("none (only the user who started the job gets its result)",
                      "the user who started the job"),
}

# Documents that describe more than one task, or a task under another name.
DOC_TASKS = {"viewlogviewlog2": ("viewlog", "viewlog2")}
NOT_TASK_DOCS = ("README", "async_readme", "template")


def load_tasks():
    """task name -> (list of authority names, connection type)."""
    tasks = {}
    for filename, connection in TABLES:
        with open(os.path.join(SRC, filename)) as f:
            src = f.read()
        start = src.index("task_info[] =\n{")
        body = src[start:src.index("\n};", start)]
        for m in re.finditer(r'\{\s*"([^"]+)",(?:[^{}]|\n)*?,\s*([A-Z_ |]+?)\s*\}',
                             body):
            words = [w.strip() for w in m.group(2).split("|")]
            unknown = [w for w in words if w != "AU_ANY" and w not in dict(BITS)]
            if unknown:
                raise SystemExit("%s: task %s: cannot read authority %s"
                                 % (filename, m.group(1), m.group(2)))
            names = [name for bit, name in BITS if bit in words]
            tasks[m.group(1)] = (names, connection)
    return tasks


def doc_text(task, tasks):
    if task in OVERRIDES:
        return OVERRIDES[task][0]
    names = tasks[task][0]
    if not names:
        return "none (any logged-in user)"
    if len(names) == 1:
        return names[0]
    return "one of " + ", ".join(names)


def cell_text(task, tasks):
    if task in OVERRIDES:
        return OVERRIDES[task][1]
    names = tasks[task][0]
    return ", ".join(names) if names else "any logged-in user"


def known(task, tasks):
    return task in tasks or task in OVERRIDES


def doc_tasks(docname):
    return DOC_TASKS.get(docname, (docname,))


def update_task_doc(path, line):
    """Put the generated line where it was, or right before the request
    syntax heading the first time. Hand-written lines after it (extra
    restrictions) are left as they are."""
    with open(path) as f:
        text = f.read()
    lines = text.split("\n")
    generated = LINE_PREFIX + line
    for i, l in enumerate(lines):
        if l.startswith(LINE_PREFIX):
            lines[i] = generated
            return text, "\n".join(lines)
    for i, l in enumerate(lines):
        if re.match(r"^## Request JSON [Ss]yntax", l):
            break
    else:
        raise SystemExit("%s: no '## Request JSON Syntax' heading" % path)
    head = lines[:i]
    while head and head[-1] == "":
        head.pop()
    return text, "\n".join(head + ["", generated, ""] + lines[i:])


ROW = re.compile(r"^\|\s*(?P<name>[^|]+?)\s*\|\s*(?P<conn>[^|]*?)\s*\|\s*(?P<perm>[^|]*?)\s*\|")


def row_tasks(name_cell):
    m = re.match(r"^\[([^\]]+)\]\(([^)]+)\)$", name_cell)
    label = m.group(1) if m else name_cell
    return label, [t for t in label.split("/")]


def update_readme(path, tasks, docs):
    with open(path) as f:
        text = f.read()
    # remove the previously generated table
    if SECTION_BEGIN in text:
        a = text.index(SECTION_BEGIN)
        b = text.index(SECTION_END) + len(SECTION_END)
        text_wo = text[:a].rstrip("\n") + "\n" + text[b:].lstrip("\n")
    else:
        text_wo = text
    out_lines, listed = [], set()
    in_interfaces = False
    for line in text_wo.split("\n"):
        if line.startswith("## "):
            # only the interface tables; the permission legend above them is
            # a table too
            in_interfaces = (line.strip() == "## CMS Interfaces")
        m = ROW.match(line) if in_interfaces else None
        if not m or m.group("name").startswith("**") or m.group("name").startswith("---"):
            out_lines.append(line)
            continue
        label, names = row_tasks(m.group("name"))
        if not all(known(t, tasks) for t in names):
            continue                    # the task no longer exists
        if label in listed:
            continue                    # duplicate row
        listed.add(label)
        listed.update(names)
        cells = sorted(set(cell_text(t, tasks) for t in names))
        if len(cells) != 1:
            raise SystemExit("README: %s: tasks of one row differ in authority" % label)
        docname = "viewlogviewlog2" if label == "viewlog/viewlog2" else label
        name = ("[%s](%s.md)" % (label, docname)) if docname in docs else label
        out_lines.append("| %s | %s | %s |" % (name, m.group("conn"), cells[0]))
    missing = sorted(t for t in tasks if t not in listed)
    text_out = "\n".join(out_lines).rstrip("\n") + "\n"
    if missing:
        rows = ["| %s | %s | %s |" % (("[%s](%s.md)" % (t, t)) if t in docs else t,
                                       tasks[t][1], cell_text(t, tasks))
                for t in missing]
        text_out += "\n".join([
            "", SECTION_BEGIN, "",
            "### Other tasks",
            "",
            "These tasks are not listed in the sections above; most of them have no",
            "document of their own yet.",
            "",
            "| **Interface Name** | **Connection Type** | **Permission** |",
            "| --- | --- | --- |"] + rows + ["", SECTION_END, ""])
    return text, text_out


def main():
    check = "--check" in sys.argv[1:]
    tasks = load_tasks()
    docs = set(f[:-3] for f in os.listdir(DOCS) if f.endswith(".md"))
    changes = []

    for docname in sorted(docs):
        if docname in NOT_TASK_DOCS:
            continue
        names = doc_tasks(docname)
        if not all(known(t, tasks) for t in names):
            raise SystemExit("%s.md: no such task in the task tables" % docname)
        lines = sorted(set(doc_text(t, tasks) for t in names))
        if len(lines) != 1:
            raise SystemExit("%s.md: its tasks differ in authority" % docname)
        path = os.path.join(DOCS, docname + ".md")
        old, new = update_task_doc(path, lines[0])
        if old != new:
            changes.append((path, new))

    path = os.path.join(DOCS, "README.md")
    old, new = update_readme(path, tasks, docs)
    if old != new:
        changes.append((path, new))

    if check:
        for path, _ in changes:
            print("out of date: %s" % os.path.relpath(path, ROOT))
        if changes:
            print("run docs/api/tools/gen_task_authority.py to update them")
            return 1
        print("API documents match the task tables (%d tasks)" % len(tasks))
        return 0

    for path, new in changes:
        with open(path, "w") as f:
            f.write(new)
        print("updated %s" % os.path.relpath(path, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
